"""CrochetPARADE DSL 导出器（外部对标研究的 P1 建议）。

把本项目的逐圈图解翻译为 CrochetPARADE（crochetparade.org）的文本语法，
供用户粘贴到其网页应用获得：可旋转 3D 模型、"过松/过紧针目"物理分析、
逐针动画与 Blender 可导入的 3D 文件——本项目代数自检之外的独立验证层
（可补充 G4 实体试钩前的检查，不替代实物验证）。本模块不运行外部仿真。

语法依据（逐条核对过的官方来源，勿凭记忆改动）：
- 每个新行 = 新的一圈；`ring` 单独一行表示魔法环（无固定默认针数）；
- `stitchNinc` / `stitchNtog`：1 针目放 N 针 / N 针并 1 针目
  （如 `sc6inc` = 一针目里 6 短针，`sc2tog` = 2 针并 1）；
- `Nstitch` = 重复 N 次（`8sc`）；`N[...]` = 方括号组重复 N 次
  （`6[sc,sc2inc]`）；
- `scfl` / `scbl` = 前 / 后半针短针；增减后缀附在其后（`scbl2tog`）。
  核对 https://github.com/stassev/CrochetPARADE/blob/main/Manual.html
  Stitch table、stitch_nameNinc/Ntog 及官方 capabilities.md §1.5；
- `start_anew`：下一针与前一针无连接（开始新部件）；
- `COLOR: <hex>` 指令作用于其后针目；`#` 行注释。
官方手册：https://crochetparade.org/Manual.html（语法核心见 Codeberg 仓库
Manual.md 与官方论坛 sphere 示例：ring / sc8inc / 8sc2inc / 8[sc,sc2inc]）。

许可边界：本模块只输出文本、不引入 CrochetPARADE 代码（其计算组件为
GPLv3，本项目 MIT——保持单向文本出口即可，无需许可合并）。
"""
from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any

from app.models.colors import present_color
from app.models.instruction_checks import instruction_issues, round_expression
from app.models.parts import _part_instance_colors
from app.models.stitch_notation import NotationError, StitchExpression, mentions_invisible_decrease
from app.schemas import MAX_ROUND_STITCHES
from app.utils.counts import integer_count as _integer_count

# 翻译器支持的针法词表与 token 白名单（emitter-level lint 用；
# 超出即拒译而非瞎猜——词表来自官方手册的核对于集）
_STITCH_VOCAB = ("sc(?:fl|bl)?|hdc|dc|tr|dtr|ch|ss|rsc")
_DSL_ATOM = re.compile(rf"(?:{_STITCH_VOCAB})(?:([0-9]+)(?:inc|tog))?")
_DSL_TOKEN = re.compile(rf"(?:{_STITCH_VOCAB})(?:[0-9]+(?:inc|tog))?|[0-9]+|[\[\],]")
_DSL_STITCH = {"X": "sc", "V": "sc2inc", "A": "sc2tog", "W": "sc3inc", "M": "sc3tog"}
_LOOP_START_ISSUE = "首圈挑针缺少可译的基底，不能按魔法环导出"

_HEADER = (
    "# Generated by CrochetPhoto2Pattern — paste into https://crochetparade.org\n"
    "# to render a rotatable 3D model and run its stitch-tension analysis.\n"
    "# Each line is one round; the magic ring (ring) is the anchor row.\n"
    "# Explicit formulas retain stitch order and scoped FLO/BLO (scfl/scbl).\n"
    "# Unresolved loop instructions stop that part. Prose-only placement and\n"
    "# finishing instructions are not executed; review them in the pattern.\n"
    "# Invisible decreases stop that part; their technique is not translated.\n"
)


def _hex_of(color: str | None, displays: Mapping[str, str] | None = None) -> str | None:
    """可导出的 hex。待选占位和没有显示色的自定义名返回 None，不写成已选线。"""
    return present_color(color, displays).export_hex


def _swatch_comment(color: object, displays: Mapping[str, str] | None) -> str | None:
    """自定义名称的显示色注释。hex 只是屏幕示意，注释写明它不是品牌色号。"""
    if not isinstance(color, str) or not isinstance(displays, Mapping) or color not in displays:
        return None
    presented = present_color(color, displays)
    if not presented.is_custom or presented.export_hex is None:
        return None
    if any(ord(char) < 32 or char == "#" for char in color):
        return None
    return f"# display swatch for {color} — screen colour only, not a yarn brand code"


def _aggregate_round_tokens(prev_stitches: int, rd: dict[str, Any]) -> list[str] | None:
    """把一圈的 (stitches, increase, decrease) 聚合量翻译为 token 序列。

    缺少可解析操作式时，仅提供由聚合数值推断的均匀分组：
    - 无加无减：`Nsc`
    - 加针 inc：`M[base_sc,sc2inc]`（M=inc，base=prev//inc-1，需整除）
    - 减针 dec：`M[base_sc,sc2tog]`（M=dec，base=prev//dec-2，需整除）
    返回 None 表示该圈形态超出可译子集（调用方记 warning 并跳过该圈）。
    """
    if not isinstance(rd, dict):
        return None
    try:
        stitches = _integer_count(rd.get("stitches", 0))
        inc = _integer_count(0 if rd.get("increase") is None else rd["increase"])
        dec = _integer_count(0 if rd.get("decrease") is None else rd["decrease"])
    except (ValueError, OverflowError):
        return None
    if stitches < 1 or inc < 0 or dec < 0 or stitches != prev_stitches + inc - dec:
        return None
    if inc and dec:
        return None  # 可钩但超出本导出器的均匀分组子集
    if inc == 0 and dec == 0:
        return [f"{stitches}sc"] if stitches > 0 else None
    groups = inc or dec
    if groups <= 0 or prev_stitches % groups:
        return None
    # 加针组消耗 base+1、产出 base+2；减针组消耗 base+2、产出
    # base+1。两者不能共用同一个 base 偏移。
    base = prev_stitches // groups - (1 if inc else 2)
    if base < 0:
        return None
    produced = groups * (base + 2 if inc else base + 1)
    if produced != stitches:
        return None
    if base == 0:
        return [f"{groups}sc2inc" if inc else f"{groups}sc2tog"]
    base_tok = "sc" if base == 1 else f"{base}sc"  # 对齐官方示例的 8[sc,sc2inc]
    body = f"{base_tok},{'sc2inc' if inc else 'sc2tog'}"
    return [f"{groups}[{body}]"]


def _expression_token(expression: StitchExpression) -> str:
    """Emit the ordered tree directly, without expanding repeated groups."""
    if expression.stitch is not None:
        symbol, _, loop = expression.stitch.partition("-")
        body = _DSL_STITCH[symbol]
        if loop:
            body = "sc" + {"FLO": "fl", "BLO": "bl"}[loop] + body[2:]
        return f"{expression.repeats}{body}" if expression.repeats != 1 else body
    body = ",".join(_expression_token(child) for child in expression.children)
    return f"{expression.repeats}[{body}]" if expression.repeats != 1 else body


def _round_translation(previous: int, rd: Any) -> tuple[str | None, bool, str]:
    """Return one DSL line, whether positions were inferred, and an error."""
    if not isinstance(rd, dict):
        return None, False, "圈记录不是对象"
    try:
        stitches = _integer_count(rd.get("stitches", 0))
        inc = _integer_count(0 if rd.get("increase") is None else rd["increase"])
        dec = _integer_count(0 if rd.get("decrease") is None else rd["decrease"])
    except (ValueError, OverflowError):
        return None, False, "针数或加减针不是有效整数"
    if (not 1 <= stitches <= MAX_ROUND_STITCHES or min(inc, dec) < 0
            or max(inc, dec) > MAX_ROUND_STITCHES or stitches != previous + inc - dec):
        return None, False, "针数或加减针与前圈不一致或超出范围"
    issues = instruction_issues(rd.get("notes"), stitches, inc, dec, previous_stitches=previous)
    if issues:
        return None, False, "；".join(issues)
    if mentions_invisible_decrease(rd.get("notes")):
        return None, False, "隐形减针不在当前 DSL 翻译子集内，请对照原说明核对工艺"
    try:
        expression = round_expression(rd.get("notes"))
    except NotationError as exc:
        return None, False, str(exc)
    if expression is not None:
        return _expression_token(expression), False, ""
    tokens = _aggregate_round_tokens(previous, rd)
    if tokens is None:
        return None, False, "缺少完整操作式，无法从聚合针数确定针位"
    return ",".join(tokens), True, ""


@dataclass
class ParadeExportReport:
    text: str = ""
    complete: bool = True
    requested_parts: int = 0  # Physical copies, not logical part definitions.
    # Only copies that are faithful AND complete. A copy whose construction the
    # exporter cannot express (e.g. an open ring start emitted as a magic ring)
    # still contributes DSL rounds, but is not a complete export.
    exported_parts: int = 0
    requested_rounds: int = 0
    # DSL rounds actually generated, including rounds of parts that are not
    # faithful. Deliberately separate from ``exported_parts``: "how many rounds
    # did we emit" and "how much of the pattern is faithfully represented" are
    # different questions, and this counter must never be read as fidelity.
    exported_rounds: int = 0
    inferred_rounds: int = 0  # Physical rounds using uniform aggregate fallback.
    warnings: list[str] = field(default_factory=list)
    # complete=False 的两类原因：导出器已声明不支持的构造（环形起针、跨部件
    # 预留半针接合），以及其他无法翻译的内容。评测只把后者计为导出失败。
    unsupported_constructions: list[dict[str, str]] = field(default_factory=list)
    failures: list[str] = field(default_factory=list)

    def fail(self, message: str) -> None:
        self.complete = False
        self.failures.append(message)
        self.warnings.append(message)

    def unsupported(self, part: str, construction: str, message: str) -> None:
        self.complete = False
        self.unsupported_constructions.append({"part": part, "construction": construction})
        self.warnings.append(message)


def _part_lines(part: dict[str, Any], report: ParadeExportReport, *, joined: bool = False,
                displays: Mapping[str, str] | None = None) -> list[str]:
    """单个部件 → DSL 行；数量 >1 的部件按 start_anew 重复输出。

    ``joined``：该部件接入其他部件的预留半针（如挑针接裙），首圈没有可译基底。
    """
    name = str(part.get("name", "?"))
    warnings = report.warnings
    try:
        quantity = _integer_count(part.get("quantity", 1))
        if not 1 <= quantity <= 20:
            raise ValueError("无效的数量")
    except (ValueError, OverflowError):
        report.fail(f"{name}: 数量无效，该部件已跳过")
        return []
    report.requested_parts += quantity
    rounds = part.get("rounds") or []
    if not isinstance(rounds, list) or not rounds:
        report.fail(f"{name}: 没有可导出的圈")
        return []
    report.requested_rounds += quantity * len(rounds)
    first = rounds[0]
    try:
        n_first = _integer_count(first.get("stitches", 0))
        first_inc = _integer_count(0 if first.get("increase") is None else first["increase"])
        first_dec = _integer_count(0 if first.get("decrease") is None else first["decrease"])
        if not 1 <= n_first <= MAX_ROUND_STITCHES or first_inc or first_dec:
            raise ValueError("无效的起针数")
    except (AttributeError, ValueError, OverflowError):
        report.fail(f"{name}: 数量或首圈针数无效，该部件已跳过")
        return []
    first_issues = instruction_issues(first.get("notes"), n_first, 0, 0)
    if mentions_invisible_decrease(first.get("notes")):
        first_issues.append("隐形减针不在当前 DSL 翻译子集内")
    loop_start = False
    try:
        first_expression = round_expression(first.get("notes"))
        if first_expression is not None and first_expression.has_loop_technique:
            loop_start = True
            first_issues.append(_LOOP_START_ISSUE)
    except NotationError as exc:
        first_issues.append(str(exc))
    if first_issues:
        message = f"{name}: 首圈说明矛盾，该部件已跳过：{'；'.join(first_issues)}"
        if joined and loop_start and first_issues == [_LOOP_START_ISSUE]:
            report.unsupported(name, "reserved_loop_join", message)
        else:
            report.fail(message)
        return []
    # 开场 COLOR 优先用首圈颜色，首圈不可导出时才用部件基础色。免责声明必须
    # 指向同一个来源，不能固定写基础色。
    first_color = first.get("color")
    opening_color = first_color if _hex_of(first_color, displays) else part.get("color")
    hex_color = _hex_of(opening_color, displays)

    lines: list[str] = []
    inferred_before = report.inferred_rounds
    # Compile each logical round once, then reuse it for identical copies.
    compiled: list[tuple[dict, str, bool]] = []
    previous = n_first
    for index, rd in enumerate(rounds[1:], 2):
        line, inferred, error = _round_translation(previous, rd)
        if line is None:
            row = rd.get("row", index) if isinstance(rd, dict) else index
            report.fail(f"{name} 第 {row} 圈形态超出可译子集：{error}；该圈及后续圈已跳过")
            break
        compiled.append((rd, line, inferred))
        previous = int(rd["stitches"])
    # F-10：环形/锁针起针（如独立裙筒腰部开口）按魔法环 scNinc 导出会把开口
    # 圆筒变成闭合圆片——语义不符。按部件判定一次：多份实体共享同一份图解，
    # 构造缺口只有一个，逐份重复只会让告警与统计虚增。标记为不完整（严格完整率
    # 不计入），并登记为导出器声明不支持的构造，评测单独统计而不当作导出失败。
    # 这些圈次仍会写进 DSL 文本：exported_rounds 有它们，exported_parts 没有。
    faithful = bool(part.get("magic_ring", False))
    if not faithful:
        report.unsupported(
            name, "ring_start",
            f"{name}: 首圈非魔法环（{n_first} 针环起），按 ring+sc{n_first}inc 导出，"
            "起针语义不符（闭合环 vs 开口），已标记为不完整；请对照原说明核对引拔/开口处理")
    # 魔法环行 + 首圈（首圈全部针目放入环：scNinc）
    # 逐份选色：某份实体整份使用自己的颜色，该份不再输出逐圈换色边界——与
    # 材料清单和 Markdown 的「该份整份使用此色」同一口径。
    overrides = _part_instance_colors(part)
    emitted_copies = 0
    for copy in range(quantity):
        override = overrides[copy] if overrides is not None and copy < len(overrides) else None
        override_hex = _hex_of(override, displays)
        # A custom name has no known RGB. Reusing the shared part color would
        # silently produce the wrong copy, so refuse that copy instead of guessing.
        if override and not override_hex:
            report.fail(f"{name} 第 {copy + 1} 份颜色「{override}」无法转换为色表或十六进制颜色；"
                        "该份已跳过，请使用 Markdown/PDF 核对")
            continue
        # Legacy round colours may also be manually chosen; missing provenance
        # cannot make an unconvertible colour faithful or safe to ignore. Keep
        # their historically available stitch-only export, but mark it partial.
        color_faithful = True
        if not override:
            unresolved = next((color for rd in rounds
                               if (color := (rd.get("color") or part.get("color")))
                               and color not in ("skin", "body") and not _hex_of(color, displays)), None)
            if unresolved:
                prefix = f"{name} 第 {copy + 1} 份颜色「{unresolved}」无法转换为色表或十六进制颜色；"
                if part.get("color_origin") == "manual":
                    report.fail(prefix + "该份已跳过，请使用 Markdown/PDF 核对")
                    continue
                report.fail(prefix + "仅导出针法，颜色未忠实表达，请使用 Markdown/PDF 核对")
                color_faithful = False
        if emitted_copies:
            lines.append("start_anew")
        emitted_copies += 1
        copy_hex = override_hex or hex_color
        if copy_hex:
            # 每份实体都重置为部件色——多份拷贝不能继承上一份的结尾色
            #（条纹部件 ×N 时尤其重要）
            comment = _swatch_comment(override if override_hex else opening_color, displays)
            if comment:
                lines.append(comment)
            lines.append(f"COLOR: {copy_hex}")
        last_color = copy_hex
        lines.append("ring")
        lines.append(f"sc{n_first}inc")
        report.exported_rounds += 1
        for rd, line, inferred in compiled:
            round_color = rd.get("color")
            color_hex = None if override_hex else _hex_of(round_color, displays)
            # 仅在换色边界输出指令（连续同色圈不重复）——条纹件（如
            # Supergurumi 蜜蜂 55 圈 6 条条纹）从逐圈重复降为每边界一条
            if color_hex and color_hex != last_color:
                comment = _swatch_comment(round_color, displays)
                if comment:
                    lines.append(comment)
                lines.append(f"COLOR: {color_hex}")
                last_color = color_hex
            lines.append(line)  # All operations in a round must share ONE line.
            report.exported_rounds += 1
            report.inferred_rounds += int(inferred)
        # 只有忠实且完整翻译的实体才计入 exported_parts：构造语义不符（环起）
        # 或翻译提前中断（compiled 不全）的实体都不计入。
        if faithful and color_faithful and len(compiled) == len(rounds) - 1:
            report.exported_parts += 1
    if report.inferred_rounds > inferred_before:
        warnings.append(
            f"{name}: {report.inferred_rounds - inferred_before} 个实体圈次缺少可解析的完整操作式，"
            "按数值均匀安排针位；请对照原说明核对特殊针法及位置"
        )
    return lines


def _valid_dsl_line(line: str) -> bool:
    """Bounded parser for the emitter's nested-repeat subset, not the full DSL."""
    tokens: list[str] = []
    offset = 0
    while offset < len(line):
        if line[offset].isspace():
            offset += 1
            continue
        match = _DSL_TOKEN.match(line, offset)
        if match is None or len(tokens) >= 1024:
            return False
        tokens.append(match[0])
        offset = match.end()
    position = 0

    def positive_count(raw: str) -> bool:
        digits = raw.lstrip("0") or "0"
        return len(digits) <= len(str(MAX_ROUND_STITCHES)) and 1 <= int(digits) <= MAX_ROUND_STITCHES

    def sequence(depth: int) -> bool:
        nonlocal position
        if depth > 12:
            return False
        while position < len(tokens):
            if tokens[position].isdigit():
                if not positive_count(tokens[position]):
                    return False
                position += 1
            if position >= len(tokens):
                return False
            token = tokens[position]
            position += 1
            if token == "[":
                if not sequence(depth + 1) or position >= len(tokens) or tokens[position] != "]":
                    return False
                position += 1
            else:
                atom = _DSL_ATOM.fullmatch(token)
                if atom is None or (atom[1] and not positive_count(atom[1])):
                    return False
            if position == len(tokens) or tokens[position] == "]":
                return True
            if tokens[position] != ",":
                return False
            position += 1
        return False

    return sequence(0) and position == len(tokens)


def lint_parade_dsl(text: str) -> list[str]:
    """emitter-level 静态自检：token 白名单 + 基本结构。

    这不是 CrochetPARADE 官方 parser（其翻译器为 GPL 的 JS/Pyodide 实现，
    不作依赖）；它保证我们的输出落在已核对过的语法子集内。
    """
    issues: list[str] = []
    for i, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            continue
        if line in ("ring", "start_anew") or re.fullmatch(r"COLOR:\s*#[0-9a-fA-F]{6}", line):
            continue
        if not _valid_dsl_line(line):
            issues.append(f"第 {i} 行无法解析的 token: {line[:160]!r}")
    return issues


def export_parade_report(result: Mapping[str, Any]) -> ParadeExportReport:
    """Return DSL, completeness, physical-copy counts and structured warnings.

    raises:
        ValueError: 结果缺 params.parts 或所有部件都不可译。
    """
    params = result.get("params") or {}
    parts = params.get("parts") or []
    if not isinstance(parts, list) or not parts:
        raise ValueError("结果缺少 params.parts，无法导出 CrochetPARADE DSL")

    report = ParadeExportReport()
    warnings = report.warnings
    connections = (params.get("stitch_attachments") or {}).get("connections") or []
    if connections:
        warnings.append("已记录跨部件预留半针接合；当前 DSL 子集不表达这类连接，"
                        "接入部件会跳过，请以完整 Markdown/PDF 的接合步骤为准")
    # 接入预留半针的一方（如挑针接裙的裙子）首圈没有可译基底
    joined = {c.get("source_part") for c in connections if isinstance(c, dict)}
    body: list[str] = []
    exported_any = False
    for part in parts:
        if not isinstance(part, dict):
            report.fail("部件格式无效，该部件已跳过")
            continue
        raw_displays = params.get("display_colors")
        displays = raw_displays if isinstance(raw_displays, Mapping) else None
        lines = _part_lines(part, report, joined=part.get("name") in joined, displays=displays)
        if not lines:
            continue
        exported_any = True
        if body:
            body.append("# ── 下一部件 ──")
            body.append("start_anew")
        body.extend(lines)
    if not exported_any:
        reason = (report.failures or report.warnings or ["所有部件均超出可译子集"])[0]
        raise ValueError(f"未能导出：{reason[:240]}")

    text = _HEADER
    if warnings:
        text += "# 注意（导出器提示）：\n"
        for w in warnings:
            text += "# - " + " ".join(w.splitlines()) + "\n"
    text += "\n".join(body) + "\n"
    report.text = text
    return report


def export_parade_dsl(result: Mapping[str, Any]) -> str:
    """Compatibility text API; partial exports carry warnings in the text."""
    return export_parade_report(result).text
